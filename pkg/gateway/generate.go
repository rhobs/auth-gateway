const (
	envoyResourcesFieldName = "resources"
	envoyConfigFilename     = "envoy.yaml"
	generatedFileHeader     = "# Generated by github.com/rhobs/auth-gateway.\n"
	headerValuePattern      = `^[^\x00-\x1f\x7f]+$`
	// EnvoyConfigDirectory is `/etc/auth-gateway`, containing the bootstrap and server TLS resources.
	EnvoyConfigDirectory = "/etc/auth-gateway"
	// APIKeyConfigDirectory is `/etc/auth-gateway/api-keys`, watched for API-key credentials.
	APIKeyConfigDirectory = EnvoyConfigDirectory + "/api-keys"
	// TrustedCADirectory is `/etc/auth-gateway-ca`, the root for CA ConfigMap files.
	TrustedCADirectory = "/etc/auth-gateway-ca"
	// EnvoyBootstrapPath is `/etc/auth-gateway/envoy.yaml`, the generated Envoy bootstrap path.
	EnvoyBootstrapPath = EnvoyConfigDirectory + "/" + envoyConfigFilename
	// APIKeyECDSPath is `/etc/auth-gateway/api-keys/api-keys.yaml`, the API-key ECDS resource path.
	APIKeyECDSPath = APIKeyConfigDirectory + "/" + apiKeySecretFilename
)

// GeneratedFile contains the bytes for one Envoy resource and the absolute path
// at which Envoy expects that resource to be available.
type GeneratedFile struct {
	// Path is the absolute location Envoy expects this resource to use.
	Path string
	// Contents is the serialized Envoy resource.
	Contents []byte
}

// GeneratedFiles names the files returned by Generate. ServerCertificateResources
// contains one SDS resource per HTTPS server. ClientCAResources contains one
// validation-context SDS resource per server selecting mTLS.
type GeneratedFiles struct {
	// EnvoyBootstrap is always present when Generate succeeds.
	EnvoyBootstrap GeneratedFile
	// ServerCertificateResources contains one SDS resource for each HTTPS server.
	ServerCertificateResources []GeneratedFile
	// ClientCAResources contains one SDS resource for each mTLS server.
	ClientCAResources []GeneratedFile
}

type envoyValidator interface {
	ValidateAll() error
}

func fileConfigSource(filename string) *core.ConfigSource {
	return &core.ConfigSource{
		ResourceApiVersion: core.ApiVersion_V3,
		ConfigSourceSpecifier: &core.ConfigSource_PathConfigSource{PathConfigSource: &core.PathConfigSource{
			Path:             filename,
			WatchedDirectory: &core.WatchedDirectory{Path: path.Dir(filename)},
		}},
	}
}

func fileDataSource(filename string) *core.DataSource {
	return &core.DataSource{Specifier: &core.DataSource_Filename{Filename: filename}}
}

func marshalEnvoyFileDiscoveryResponse(resource proto.Message) ([]byte, error) {
	packed, err := packEnvoy(resource)
	if err != nil {
		return nil, err
	}
	resourceData, err := marshalEnvoyYAML(packed)
	if err != nil {
		return nil, err
	}
	var document any
	if err := yaml.Unmarshal(resourceData, &document); err != nil {
		return nil, fmt.Errorf("decode packed discovery resource: %w", err)
	}
	data, err := yaml.Marshal(map[string]any{envoyResourcesFieldName: []any{document}})
	if err != nil {
		return nil, fmt.Errorf("encode file discovery response: %w", err)
	}
	return data, nil
}

// Generate builds Envoy files from the high-level gateway configuration. Each
// returned file includes its absolute path and contents.
func Generate(c gatewayapi.Config) (GeneratedFiles, error) {
	effective, err := resolveConfig(c)
	if err != nil {
		return GeneratedFiles{}, err
	}
	contents, err := generate(effective)
	if err != nil {
		return GeneratedFiles{}, err
	}

	files := GeneratedFiles{
		EnvoyBootstrap: GeneratedFile{
			Path:     EnvoyBootstrapPath,
			Contents: contents[envoyConfigFilename],
		},
	}
	for index, server := range effective.servers {
		if server.TLSConfig == nil {
			continue
		}
		filename := serverTLSResourceFilename(index)
		files.ServerCertificateResources = append(files.ServerCertificateResources, GeneratedFile{
			Path:     path.Join(EnvoyConfigDirectory, filename),
			Contents: contents[filename],
		})
		if server.usesMTLS() {
			caFilename := clientCAResourceFilename(index)
			files.ClientCAResources = append(files.ClientCAResources, GeneratedFile{
				Path:     path.Join(EnvoyConfigDirectory, caFilename),
				Contents: contents[caFilename],
			})
		}
	}
	return files, nil
}

func generate(effective resolvedConfig) (map[string][]byte, error) {
	bootstrapConfig, err := generateBootstrap(effective)
	if err != nil {
		return nil, err
	}
	return generateFiles(effective, bootstrapConfig)
}

func generateFiles(c resolvedConfig, bootstrapConfig *bootstrap.Bootstrap) (map[string][]byte, error) {
	data, err := marshalEnvoyYAML(bootstrapConfig)
	if err != nil {
		return nil, fmt.Errorf("encode Envoy bootstrap: %w", err)
	}
	files := map[string][]byte{envoyConfigFilename: append([]byte(generatedFileHeader), data...)}
	if err := addServerCertificateFiles(c, files); err != nil {
		return nil, err
	}
	if err := addClientCAFiles(c, files); err != nil {
		return nil, err
	}
	return files, nil
}

func addServerCertificateFiles(c resolvedConfig, files map[string][]byte) error {
	for i, server := range c.servers {
		if server.TLSConfig == nil {
			continue
		}
		data, err := marshalEnvoyFileDiscoveryResponse(serverTLSSecret(*server.TLSConfig, i))
		if err != nil {
			return fmt.Errorf("servers[%d] certificate SDS resource: %w", i, err)
		}
		files[serverTLSResourceFilename(i)] = append([]byte(generatedFileHeader), data...)
	}
	return nil
}

func addClientCAFiles(c resolvedConfig, files map[string][]byte) error {
	for index, server := range c.servers {
		if !server.usesMTLS() {
			continue
		}
		data, err := marshalEnvoyFileDiscoveryResponse(clientCASecret(*server.mtls.MTLS, index))
		if err != nil {
			return fmt.Errorf("servers[%d] client CA SDS resource: %w", index, err)
		}
		files[clientCAResourceFilename(index)] = append([]byte(generatedFileHeader), data...)
	}
	return nil
}

// All returns the generated files in bootstrap, server, and client CA order.
func (files GeneratedFiles) All() []GeneratedFile {
	result := make([]GeneratedFile, 0, 1+len(files.ServerCertificateResources)+len(files.ClientCAResources))
	if files.EnvoyBootstrap.Path != "" {
		result = append(result, files.EnvoyBootstrap)
	}
	result = append(result, files.ServerCertificateResources...)
	result = append(result, files.ClientCAResources...)
	return result
}

func protobufDuration(duration *gatewayapi.Duration) *durationpb.Duration {
	return durationpb.New(time.Duration(*duration))
}

func optionalUint32(value *uint32) *wrapperspb.UInt32Value {
	if value == nil {
		return nil
	}
	return wrapperspb.UInt32(*value)
}

func socket(address string, port uint32) *core.Address {
	return &core.Address{Address: &core.Address_SocketAddress{SocketAddress: &core.SocketAddress{
		Address: address,
		PortSpecifier: &core.SocketAddress_PortValue{
			PortValue: port,
		},
	}}}
}

func packEnvoy(message proto.Message) (*anypb.Any, error) {
	if validatable, ok := message.(envoyValidator); ok {
		if err := validatable.ValidateAll(); err != nil {
			return nil, fmt.Errorf("validate %s: %w", message.ProtoReflect().Descriptor().FullName(), err)
		}
	}
	packed, err := anypb.New(message)
	if err != nil {
		return nil, fmt.Errorf("pack %s: %w", message.ProtoReflect().Descriptor().FullName(), err)
	}
	return packed, nil
}

func marshalEnvoyYAML(message proto.Message) ([]byte, error) {
	if validatable, ok := message.(envoyValidator); ok {
		if err := validatable.ValidateAll(); err != nil {
			return nil, fmt.Errorf("validate %s: %w", message.ProtoReflect().Descriptor().FullName(), err)
		}
	}
	data, err := protojson.MarshalOptions{UseProtoNames: true}.Marshal(message)
	if err != nil {
		return nil, fmt.Errorf("encode %s: %w", message.ProtoReflect().Descriptor().FullName(), err)
	}
	var value any
	if err := yaml.Unmarshal(data, &value); err != nil {
		return nil, fmt.Errorf("encode %s: convert JSON to YAML: %w", message.ProtoReflect().Descriptor().FullName(), err)
	}
	data, err = yaml.Marshal(value)
	if err != nil {
		return nil, fmt.Errorf("encode %s: marshal YAML: %w", message.ProtoReflect().Descriptor().FullName(), err)
	}
	return data, nil
}
