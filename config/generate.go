// Generate builds Envoy files from the high-level gateway configuration. Each
// returned file includes its absolute path and contents.
func Generate(c Config) (GeneratedFiles, error) {
	effective, err := resolveConfig(c)
	if err != nil {
		return GeneratedFiles{}, err
	}
	contents, err := generate(effective)
	if err != nil {
		return GeneratedFiles{}, err
	}

	files := GeneratedFiles{
		EnvoyBootstrap: GeneratedFile{
			Path:     EnvoyBootstrapPath,
			Contents: contents[envoyConfigFilename],
		},
	}
	if processing, ok := contents[processingConfigFilename]; ok {
		files.ProcessingConfig = &GeneratedFile{
			Path:     ProcessingConfigPath,
			Contents: processing,
		}
	}
	for index, server := range effective.Servers {
		if server.TLSConfig == nil {
			continue
		}
		filename := serverTLSResourceFilename(index)
		files.ServerCertificateResources = append(files.ServerCertificateResources, GeneratedFile{
			Path:     path.Join(EnvoyConfigDirectory, filename),
			Contents: contents[filename],
		})
	}
	return files, nil
}

func generate(effective effectiveConfig) (map[string][]byte, error) {
	bootstrapConfig, err := generateBootstrap(effective.Config)
	if err != nil {
		return nil, err
	}
	return generateFiles(effective.Config, bootstrapConfig)
}

func generateBootstrap(c Config) (*bootstrap.Bootstrap, error) {
	clusters, err := generateClusters(c)
	if err != nil {
		return nil, err
	}
	filterChains, err := generateFilterChains(c)
	if err != nil {
		return nil, err
	}
	listenerFilters, err := generateListenerFilters(c)
	if err != nil {
		return nil, err
	}
	bootstrapConfig := &bootstrap.Bootstrap{
		Node:  &core.Node{Id: c.Node.ID, Cluster: c.Node.Cluster},
		Admin: &bootstrap.Admin{Address: socket(envoyAdminAddress, envoyAdminPort)},
		StaticResources: &bootstrap.Bootstrap_StaticResources{
			Listeners: []*listener.Listener{{
				Name:                          ingestionListenerName,
				Address:                       socket(envoyListenerAddress, *c.Listener.Port),
				PerConnectionBufferLimitBytes: optionalUint32(c.Listener.PerConnectionBufferLimitBytes),
				ListenerFilters:               listenerFilters,
				FilterChains:                  filterChains,
			}},
			Clusters: clusters,
		},
	}
	if c.Overload != nil {
		bootstrapConfig.OverloadManager, err = c.Overload.toOverloadManager()
		if err != nil {
			return nil, err
		}
	}
	if c.hasRequestMetrics() {
		bootstrapConfig.StatsConfig = requestMetricsStatsConfig(c.APIs, c.requestMetricName())
	}
	return bootstrapConfig, nil
}

func generateClusters(c Config) ([]*cluster.Cluster, error) {
	clusters, err := apiClusters(c.APIs)
	if err != nil {
		return nil, err
	}
	jwks, err := jwksClusters(c.Authenticators, c.Servers)
	if err != nil {
		return nil, err
	}
	clusters = append(clusters, jwks...)
	if c.Observability.Tracing.enabled() {
		tracingCluster, err := otelTraceCluster()
		if err != nil {
			return nil, fmt.Errorf("OpenTelemetry trace cluster: %w", err)
		}
		clusters = append(clusters, tracingCluster)
	}
	return clusters, nil
}

type indexedVirtualHost struct {
	serverIndex int
	host        *route.VirtualHost
}

func routeVirtualHosts(hosts []indexedVirtualHost) []*route.VirtualHost {
	virtualHosts := make([]*route.VirtualHost, len(hosts))
	for i, host := range hosts {
		virtualHosts[i] = host.host
	}
	return virtualHosts
}

func generateFilterChains(c Config) ([]*listener.FilterChain, error) {
	apis := c.apisByName()
	var filterChains []*listener.FilterChain
	var httpHosts []indexedVirtualHost
	for i, server := range c.Servers {
		host, err := serverVirtualHost(c, i, server, apis)
		if err != nil {
			return nil, err
		}
		indexedHost := indexedVirtualHost{serverIndex: i, host: host}
		if server.TLSConfig == nil {
			httpHosts = append(httpHosts, indexedHost)
			continue
		}
		chain, err := c.toHTTPFilterChain([]indexedVirtualHost{indexedHost})
		if err != nil {
			return nil, fmt.Errorf("servers[%d]: %w", i, err)
		}
		chain.FilterChainMatch = &listener.FilterChainMatch{TransportProtocol: "tls", ServerNames: []string{server.Hostname}}
		chain.TransportSocket, err = serverTLSTransportSocket(i)
		if err != nil {
			return nil, fmt.Errorf("servers[%d] downstream TLS context: %w", i, err)
		}
		chain.TransportSocketConnectTimeout = c.Listener.TLSHandshakeTimeout.protobuf()
		filterChains = append(filterChains, chain)
	}
	if len(httpHosts) > 0 {
		chain, err := c.toHTTPFilterChain(httpHosts)
		if err != nil {
			return nil, err
		}
		if c.hasHTTPS() {
			chain.FilterChainMatch = &listener.FilterChainMatch{TransportProtocol: "raw_buffer"}
		}
		filterChains = append([]*listener.FilterChain{chain}, filterChains...)
	}
	return filterChains, nil
}

func serverVirtualHost(c Config, index int, server Server, apis map[string]API) (*route.VirtualHost, error) {
	bound, err := server.boundAPIs(apis)
	if err != nil {
		return nil, fmt.Errorf("servers[%d].apis: %w", index, err)
	}
	routes, err := apiRoutesWithRequestHeaderMutations(bound, c.hasAuthenticationConfig())
	if err != nil {
		return nil, fmt.Errorf("servers[%d] routes: %w", index, err)
	}
	host := &route.VirtualHost{Name: server.Hostname, Domains: []string{server.Hostname}, Routes: routes}
	if server.Authentication == nil {
		return host, nil
	}
	host.TypedPerFilterConfig = make(map[string]*anypb.Any)
	if err := addServerJWTRequirement(c, host, index, server); err != nil {
		return nil, err
	}
	if err := addServerAPIKeyConfig(c, host, index, server); err != nil {
		return nil, err
	}
	rbacConfig, err := packEnvoy(&httpRBAC.RBACPerRoute{Rbac: &httpRBAC.RBAC{Rules: c.toServerRBACRules(server)}})
	if err != nil {
		return nil, fmt.Errorf("servers[%d] RBAC rules: %w", index, err)
	}
	host.TypedPerFilterConfig[authorizationFilterName] = rbacConfig
	return host, nil
}

func addServerJWTRequirement(c Config, host *route.VirtualHost, index int, server Server) error {
	if !serverUsesJWT(c, server) {
		return nil
	}
	requirementName := serverJWTRequirementName(index)
	perRoute, err := packEnvoy(&jwt.PerRouteConfig{RequirementSpecifier: &jwt.PerRouteConfig_RequirementName{RequirementName: requirementName}})
	if err != nil {
		return fmt.Errorf("servers[%d] JWT requirement: %w", index, err)
	}
	host.TypedPerFilterConfig[jwtAuthnFilterName] = perRoute
	return nil
}

func addServerAPIKeyConfig(c Config, host *route.VirtualHost, index int, server Server) error {
	if !serverUsesAPIKey(c, server) {
		return nil
	}
	perRoute, err := c.toAPIKeyPerRouteConfig(server)
	if err != nil {
		return fmt.Errorf("servers[%d] API-key matcher: %w", index, err)
	}
	host.TypedPerFilterConfig[apiKeyFilterName] = perRoute
	authentication, err := packEnvoy(&httpRBAC.RBACPerRoute{Rbac: &httpRBAC.RBAC{Rules: c.toServerAuthenticationRBACRules(server)}})
	if err != nil {
		return fmt.Errorf("servers[%d] authentication rules: %w", index, err)
	}
	host.TypedPerFilterConfig[authenticationFilterName] = authentication
	return nil
}

func generateListenerFilters(c Config) ([]*listener.ListenerFilter, error) {
	if !c.hasHTTPS() {
		return nil, nil
	}
	inspectorConfig, err := packEnvoy(&inspector.TlsInspector{})
	if err != nil {
		return nil, fmt.Errorf("encode TLS inspector: %w", err)
	}
	return []*listener.ListenerFilter{{
		Name:       tlsInspectorFilterName,
		ConfigType: &listener.ListenerFilter_TypedConfig{TypedConfig: inspectorConfig},
	}}, nil
}

func generateFiles(c Config, bootstrapConfig *bootstrap.Bootstrap) (map[string][]byte, error) {
	data, err := marshalEnvoyYAML(bootstrapConfig)
	if err != nil {
		return nil, fmt.Errorf("encode Envoy bootstrap: %w", err)
	}
	files := map[string][]byte{envoyConfigFilename: append([]byte(generatedFileHeader), data...)}
	if c.hasAttributeMappings() {
		if err := addProcessingConfigFile(c, files); err != nil {
			return nil, err
		}
	}
	if err := addServerCertificateFiles(c, files); err != nil {
		return nil, err
	}
	return files, nil
}

func addProcessingConfigFile(c Config, files map[string][]byte) error {
	resource, err := c.toProcessingECDSResource()
	if err != nil {
		return fmt.Errorf("encode attribute processing ECDS resource: %w", err)
	}
	data, err := marshalEnvoyFileDiscoveryResponse(resource)
	if err != nil {
		return fmt.Errorf("encode attribute processing ECDS response: %w", err)
	}
	files[processingConfigFilename] = append([]byte(generatedFileHeader), data...)
	return nil
}

func addServerCertificateFiles(c Config, files map[string][]byte) error {
	for i, server := range c.Servers {
		if server.TLSConfig == nil {
			continue
		}
		data, err := marshalEnvoyFileDiscoveryResponse(server.TLSConfig.toEnvoySecret(i))
		if err != nil {
			return fmt.Errorf("servers[%d] certificate SDS resource: %w", i, err)
		}
		files[serverTLSResourceFilename(i)] = append([]byte(generatedFileHeader), data...)
	}
	return nil
}

func (c Config) toHTTPFilterChain(hosts []indexedVirtualHost) (*listener.FilterChain, error) {
	manager, err := c.toHTTPManager(hosts)
	if err != nil {
		return nil, err
	}
	managerConfig, err := packEnvoy(manager)
	if err != nil {
		return nil, fmt.Errorf("encode HTTP connection manager: %w", err)
	}
	return &listener.FilterChain{Filters: []*listener.Filter{{
		Name:       httpConnectionManagerName,
		ConfigType: &listener.Filter_TypedConfig{TypedConfig: managerConfig},
	}}}, nil
}

func (c Config) toHTTPManager(hosts []indexedVirtualHost) (*hcm.HttpConnectionManager, error) {
	routerConfig, err := packEnvoy(&router.Router{SuppressEnvoyHeaders: true})
	if err != nil {
		return nil, err
	}
	accessLogs, err := errorAccessLogs()
	if err != nil {
		return nil, err
	}
	virtualHosts := routeVirtualHosts(hosts)
	protected := hasProtectedHosts(hosts)
	filters, err := c.toHTTPFilters(hosts, protected)
	if err != nil {
		return nil, err
	}
	filters = append(filters, &hcm.HttpFilter{Name: routerFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: routerConfig}})
	tracing, err := c.Observability.Tracing.toEnvoyTracingConfig()
	if err != nil {
		return nil, err
	}
	var http2Options *core.Http2ProtocolOptions
	if c.Listener.HTTP2 != nil {
		http2Options = c.Listener.HTTP2.envoy()
	}
	return &hcm.HttpConnectionManager{
		StatPrefix:            httpManagerStatPrefix,
		CodecType:             hcm.HttpConnectionManager_AUTO,
		MaxRequestHeadersKb:   optionalUint32(c.Listener.MaxRequestHeadersKB),
		RequestHeadersTimeout: c.Listener.RequestHeadersTimeout.protobuf(),
		StreamIdleTimeout:     c.Listener.StreamIdleTimeout.protobuf(),
		StreamFlushTimeout:    c.Listener.StreamFlushTimeout.protobuf(),
		Http2ProtocolOptions:  http2Options,
		CommonHttpProtocolOptions: &core.HttpProtocolOptions{
			IdleTimeout:                  c.Listener.ConnectionIdleTimeout.protobuf(),
			MaxStreamDuration:            c.Listener.MaxStreamDuration.protobuf(),
			MaxHeadersCount:              optionalUint32(c.Listener.MaxRequestHeadersCount),
			HeadersWithUnderscoresAction: core.HttpProtocolOptions_REJECT_REQUEST,
		},
		RequestTimeout:               c.Listener.RequestTimeout.protobuf(),
		NormalizePath:                wrapperspb.Bool(false),
		PathWithEscapedSlashesAction: hcm.HttpConnectionManager_KEEP_UNCHANGED,
		Tracing:                      tracing,
		RouteSpecifier: &hcm.HttpConnectionManager_RouteConfig{RouteConfig: &route.RouteConfiguration{
			Name:                     ingestionListenerName,
			IgnorePortInHostMatching: true,
			VirtualHosts:             virtualHosts,
		}},
		AccessLog:   accessLogs,
		HttpFilters: filters,
	}, nil
}

func (c Config) toHTTPFilters(hosts []indexedVirtualHost, protected bool) ([]*hcm.HttpFilter, error) {
	filters, err := c.requestControlFilters(routeVirtualHosts(hosts))
	if err != nil {
		return nil, err
	}
	if protected {
		filters, err = c.protectedHTTPFilters(filters, hosts)
		if err != nil {
			return nil, err
		}
	}
	if c.usesAPIKeys() && !protected {
		cleanup, err := c.toCredentialCleanupFilter()
		if err != nil {
			return nil, err
		}
		filters = append(filters, cleanup)
	}
	return filters, nil
}

func (c Config) requestControlFilters(hosts []*route.VirtualHost) ([]*hcm.HttpFilter, error) {
	var identityHeaders []string
	if c.usesAPIKeys() {
		identityHeaders = append(identityHeaders, apiKeyClientHeader)
		for _, authenticator := range c.Authenticators {
			if authenticator.JWT != nil {
				identityHeaders = append(identityHeaders, jwtVerifiedHeaderName(authenticator.Name))
			}
		}
	}
	controls, err := packEnvoy(requestControlMutations(identityHeaders...))
	if err != nil {
		return nil, fmt.Errorf("encode request-control header removal: %w", err)
	}
	filters := []*hcm.HttpFilter{{Name: requestControlsFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: controls}}}
	if !hasRequestMetricRoutes(hosts) {
		return filters, nil
	}
	metricConfig, err := packEnvoy(&lua.Lua{DefaultSourceCode: &core.DataSource{
		Specifier: &core.DataSource_InlineString{InlineString: requestMetricsLuaScript(c.APIs, c.requestMetricName())},
	}})
	if err != nil {
		return nil, fmt.Errorf("encode request metrics Lua filter: %w", err)
	}
	filters = append(filters, &hcm.HttpFilter{Name: requestMetricsFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: metricConfig}})
	return filters, nil
}

func (c Config) protectedHTTPFilters(filters []*hcm.HttpFilter, hosts []indexedVirtualHost) ([]*hcm.HttpFilter, error) {
	usesJWT, usesKey := false, false
	serverIndexes := make([]int, 0, len(hosts))
	for _, host := range hosts {
		serverIndexes = append(serverIndexes, host.serverIndex)
		usesJWT = usesJWT || serverUsesJWT(c, c.Servers[host.serverIndex])
		usesKey = usesKey || serverUsesAPIKey(c, c.Servers[host.serverIndex])
	}
	var err error
	filters, err = c.authenticationHTTPFilters(filters, serverIndexes, usesJWT, usesKey)
	if err != nil {
		return nil, err
	}
	if needsWorkingAttributes(c) {
		filters, err = c.attributeHTTPFilters(filters, hosts)
		if err != nil {
			return nil, err
		}
	}
	return c.authorizationHTTPFilters(filters)
}

func (c Config) authenticationHTTPFilters(filters []*hcm.HttpFilter, serverIndexes []int, usesJWT, usesKey bool) ([]*hcm.HttpFilter, error) {
	if usesJWT {
		var jwtConfig *jwt.JwtAuthentication
		var err error
		if c.usesAPIKeys() {
			jwtConfig, err = c.toJWTFilterConfig(serverIndexes...)
		} else {
			jwtConfig, err = c.toJWTFilterConfig()
		}
		if err != nil {
			return nil, err
		}
		packed, err := packEnvoy(jwtConfig)
		if err != nil {
			return nil, fmt.Errorf("encode JWT authentication filter: %w", err)
		}
		filters = append(filters, &hcm.HttpFilter{Name: jwtAuthnFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: packed}})
	}
	headers := requestHeaderSources(c, serverIndexes)
	var keyAuthenticator Authenticator
	if usesKey {
		filters = append(filters, apiKeyFilter())
		keyAuthenticator, _ = c.apiKeyAuthenticator()
	}
	if usesKey || len(headers) > 0 {
		metadata, err := keyAuthenticator.toRequestMetadataFilter(headers)
		if err != nil {
			return nil, fmt.Errorf("encode request metadata filter: %w", err)
		}
		filters = append(filters, metadata)
	}
	if usesKey {
		var err error
		filters, err = appendAuthenticationRBAC(filters)
		if err != nil {
			return nil, err
		}
	}
	return filters, nil
}

func appendAuthenticationRBAC(filters []*hcm.HttpFilter) ([]*hcm.HttpFilter, error) {
	authentication, err := packEnvoy(&httpRBAC.RBAC{})
	if err != nil {
		return nil, fmt.Errorf("encode authentication RBAC filter: %w", err)
	}
	return append(filters, &hcm.HttpFilter{Name: authenticationFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: authentication}}), nil
}

func (c Config) attributeHTTPFilters(filters []*hcm.HttpFilter, hosts []indexedVirtualHost) ([]*hcm.HttpFilter, error) {
	if c.usesAPIKeys() {
		var err error
		filters, err = c.apiKeyAttributeFilters(filters, hosts)
		if err != nil {
			return nil, err
		}
	} else {
		if !c.hasAttributeMappings() {
			attributeFilter := &hcm.HttpFilter{Name: attributeFilterName}
			attributeConfig, err := packEnvoy(c.toAttributeInitializationConfig())
			if err != nil {
				return nil, fmt.Errorf("encode attribute initialization filter: %w", err)
			}
			attributeFilter.ConfigType = &hcm.HttpFilter_TypedConfig{TypedConfig: attributeConfig}
			filters = append(filters, attributeFilter)
		}
	}
	if c.hasAttributeMappings() {
		filters = append(filters, &hcm.HttpFilter{Name: attributeFilterName, ConfigType: &hcm.HttpFilter_ConfigDiscovery{ConfigDiscovery: &core.ExtensionConfigSource{
			ConfigSource: fileConfigSource(ProcessingConfigPath),
			TypeUrls:     []string{string((&setfilterstate.Config{}).ProtoReflect().Descriptor().FullName())},
		}}})
	}
	return filters, nil
}

func (c Config) apiKeyAttributeFilters(filters []*hcm.HttpFilter, hosts []indexedVirtualHost) ([]*hcm.HttpFilter, error) {
	for _, indexedHost := range hosts {
		serverIndex := indexedHost.serverIndex
		attributes := c.toServerAttributeInitializationConfig(c.Servers[serverIndex])
		if len(attributes.OnRequestHeaders) == 0 {
			continue
		}
		packed, err := packEnvoy(attributes)
		if err != nil {
			return nil, fmt.Errorf("servers[%d] attribute initialization: %w", serverIndex, err)
		}
		name := attributeInitializationFilterName(serverIndex)
		filters = append(filters, &hcm.HttpFilter{Name: name, Disabled: true, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: packed}})
		enableConfig, err := packEnvoy(&setfilterstate.Config{})
		if err != nil {
			return nil, fmt.Errorf(enableAttributesErrorFormat, serverIndex, err)
		}
		enabled, err := packEnvoy(&route.FilterConfig{Config: enableConfig})
		if err != nil {
			return nil, fmt.Errorf(enableAttributesErrorFormat, serverIndex, err)
		}
		if indexedHost.host == nil {
			return nil, fmt.Errorf("servers[%d] enable attributes: virtual host is nil", serverIndex)
		}
		if indexedHost.host.TypedPerFilterConfig == nil {
			indexedHost.host.TypedPerFilterConfig = make(map[string]*anypb.Any)
		}
		indexedHost.host.TypedPerFilterConfig[name] = enabled
	}
	return filters, nil
}

func (c Config) authorizationHTTPFilters(filters []*hcm.HttpFilter) ([]*hcm.HttpFilter, error) {
	rbacConfig, err := packEnvoy(&httpRBAC.RBAC{})
	if err != nil {
		return nil, fmt.Errorf("encode RBAC filter: %w", err)
	}
	filters = append(filters, &hcm.HttpFilter{Name: authorizationFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: rbacConfig}})
	if hasRequestHeaderProcessing(c.APIs) {
		filters, err = appendRequiredHeaderRBAC(filters)
		if err != nil {
			return nil, err
		}
	}
	if c.usesAPIKeys() {
		cleanup, err := c.toCredentialCleanupFilter()
		if err != nil {
			return nil, err
		}
		filters = append(filters, cleanup)
	}
	if hasRequestHeaderProcessing(c.APIs) {
		headerMutationConfig, err := packEnvoy(requestHeaderMutationConfig(c.APIs))
		if err != nil {
			return nil, fmt.Errorf("encode request header mutation filter: %w", err)
		}
		filters = append(filters, &hcm.HttpFilter{Name: headerMutationFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: headerMutationConfig}})
	}
	return filters, nil
}

func appendRequiredHeaderRBAC(filters []*hcm.HttpFilter) ([]*hcm.HttpFilter, error) {
	headerRBACConfig, err := packEnvoy(&httpRBAC.RBAC{})
	if err != nil {
		return nil, fmt.Errorf("encode required-header RBAC filter: %w", err)
	}
	return append(filters, &hcm.HttpFilter{Name: requiredHeaderFilterName, ConfigType: &hcm.HttpFilter_TypedConfig{TypedConfig: headerRBACConfig}}), nil
}

func hasProtectedHosts(hosts []indexedVirtualHost) bool {
	for _, host := range hosts {
		if host.host != nil && host.host.TypedPerFilterConfig[authorizationFilterName] != nil {
			return true
		}
	}
	return false
}

func serverJWTRequirementName(index int) string { return "server-" + strconv.Itoa(index) }

func (c Config) toJWTFilterConfig(serverIndexes ...int) (*jwt.JwtAuthentication, error) {
	config := &jwt.JwtAuthentication{Providers: map[string]*jwt.JwtProvider{}, RequirementMap: map[string]*jwt.JwtRequirement{}, StripFailureResponse: true}
	if len(serverIndexes) == 0 {
		for index := range c.Servers {
			serverIndexes = append(serverIndexes, index)
		}
	}
	used := make(map[string]struct{})
	permissive := false
	for _, index := range serverIndexes {
		server := c.Servers[index]
		permissive = permissive || mixedAnyOf(c, server)
		for _, name := range selectedAuthenticatorNames(server) {
			used[name] = struct{}{}
		}
	}
	for _, authenticator := range c.Authenticators {
		if authenticator.JWT == nil {
			continue
		}
		if _, exists := used[authenticator.Name]; !exists {
			continue
		}
		provider := &jwt.JwtProvider{
			Issuer:            authenticator.JWT.Issuer,
			Audiences:         authenticator.JWT.Audiences,
			RequireExpiration: true,
			JwksSourceSpecifier: &jwt.JwtProvider_RemoteJwks{RemoteJwks: &jwt.RemoteJwks{
				HttpUri:       &core.HttpUri{Uri: authenticator.JWT.JWKS.URI, HttpUpstreamType: &core.HttpUri_Cluster{Cluster: jwksClusterName(authenticator.Name)}, Timeout: authenticator.JWT.JWKS.FetchTimeout.protobuf()},
				CacheDuration: authenticator.JWT.JWKS.CacheDuration.protobuf(),
			}},
			FromHeaders:       []*jwt.JwtHeader{{Name: "Authorization", ValuePrefix: "Bearer "}},
			PayloadInMetadata: authenticator.Name,
		}
		if permissive {
			provider.ClaimToHeaders = []*jwt.JwtClaimToHeader{{HeaderName: jwtVerifiedHeaderName(authenticator.Name), ClaimName: jwtIssuerClaimName}}
		}
		config.Providers[authenticator.Name] = provider
	}
	for _, index := range serverIndexes {
		server := c.Servers[index]
		if server.Authentication == nil || !serverUsesJWT(c, server) {
			continue
		}
		names := selectedAuthenticatorNames(server)
		requirements := make([]*jwt.JwtRequirement, 0, len(names))
		for _, name := range names {
			if findAuthenticator(c, name).JWT != nil {
				requirements = append(requirements, &jwt.JwtRequirement{RequiresType: &jwt.JwtRequirement_ProviderName{ProviderName: name}})
			}
		}
		var requirement *jwt.JwtRequirement
		if mixedAnyOf(c, server) {
			requirement = &jwt.JwtRequirement{RequiresType: &jwt.JwtRequirement_AllowMissingOrFailed{AllowMissingOrFailed: &emptypb.Empty{}}}
		} else if len(requirements) == 1 {
			requirement = requirements[0]
		} else if len(server.Authentication.AllOf) > 0 {
			requirement = &jwt.JwtRequirement{RequiresType: &jwt.JwtRequirement_RequiresAll{RequiresAll: &jwt.JwtRequirementAndList{Requirements: requirements}}}
		} else {
			requirement = &jwt.JwtRequirement{RequiresType: &jwt.JwtRequirement_RequiresAny{RequiresAny: &jwt.JwtRequirementOrList{Requirements: requirements}}}
		}
		config.RequirementMap[serverJWTRequirementName(index)] = requirement
	}
	return config, nil
}

func (c Config) toServerRBACRules(server Server) *rbac.RBAC {
	policies := map[string]*rbac.Policy{
		localResponsePolicyName: {
			Permissions: []*rbac.Permission{apiPermission(localResponseAPIName)},
			Principals:  []*rbac.Principal{{Identifier: &rbac.Principal_Any{Any: true}}},
		},
	}
	if server.Authorization != nil {
		for _, apiName := range server.APIs {
			var principal *rbac.Principal
			if len(server.Authorization.AnyOf) > 0 {
				var grants []*rbac.Principal
				for _, policyName := range server.Authorization.AnyOf {
					grants = append(grants, c.grantPrincipalsForAPI(server, apiName, policyName)...)
				}
				if len(grants) > 0 {
					principal = &rbac.Principal{Identifier: &rbac.Principal_OrIds{OrIds: &rbac.Principal_Set{Ids: grants}}}
				}
			} else {
				var policyPrincipals []*rbac.Principal
				allowed := true
				for _, policyName := range server.Authorization.AllOf {
					grants := c.grantPrincipalsForAPI(server, apiName, policyName)
					if len(grants) == 0 {
						allowed = false
						break
					}
					policyPrincipals = append(policyPrincipals, &rbac.Principal{Identifier: &rbac.Principal_OrIds{OrIds: &rbac.Principal_Set{Ids: grants}}})
				}
				if allowed {
					principal = &rbac.Principal{Identifier: &rbac.Principal_AndIds{AndIds: &rbac.Principal_Set{Ids: policyPrincipals}}}
				}
			}
			if principal != nil {
				policies["api-"+apiName] = &rbac.Policy{Permissions: []*rbac.Permission{apiPermission(apiName)}, Principals: []*rbac.Principal{principal}}
			}
		}
	}
	return &rbac.RBAC{Action: rbac.RBAC_ALLOW, Policies: policies}
}

func (c Config) grantPrincipalsForAPI(server Server, apiName, policyName string) []*rbac.Principal {
	var grants []*rbac.Principal
	for _, grant := range authorizationPolicy(c, policyName).Grants {
		if slices.Contains(grant.APIs, apiName) && (!c.usesAPIKeys() || serverSelectsAuthenticator(server, grant.Authenticator)) {
			grants = append(grants, c.toGrantPrincipalForServer(server, grant))
		}
	}
	return grants
}

func authorizationPolicy(c Config, name string) AuthorizationPolicy {
	for _, policy := range c.AuthorizationPolicies {
		if policy.Name == name {
			return policy
		}
	}
	return AuthorizationPolicy{}
}

func apiPermission(api string) *rbac.Permission {
	return &rbac.Permission{Rule: &rbac.Permission_SourcedMetadata{SourcedMetadata: &rbac.SourcedMetadata{MetadataSource: rbac.MetadataSource_ROUTE, MetadataMatcher: &matcher.MetadataMatcher{
		Filter: authorizationFilterName, Path: []*matcher.MetadataMatcher_PathSegment{metadataPathSegment(apiMetadataName)},
		Value: &matcher.ValueMatcher{MatchPattern: &matcher.ValueMatcher_StringMatch{StringMatch: &matcher.StringMatcher{MatchPattern: &matcher.StringMatcher_Exact{Exact: api}}}},
	}}}}
}

func (c Config) toGrantPrincipal(grant AuthorizationGrant) *rbac.Principal {
	authenticator := findAuthenticator(c, grant.Authenticator)
	if authenticator.APIKey != nil {
		return authenticator.toKeyGrantPrincipal(grant)
	}
	conditions := make([]*rbac.Principal, 0, len(grant.Attributes)+1)
	hasClaim := false
	for _, attribute := range slices.Sorted(maps.Keys(grant.Attributes)) {
		source := authenticator.Attributes[attribute]
		if source.Header != nil {
			namespace, path := attributeMetadataPath(authenticator, attribute)
			conditions = append(conditions, dynamicMetadataPrincipal(namespace, path, allowedStringValueMatcher(grant.Attributes[attribute])))
		} else {
			hasClaim = true
			claimPath := append([]string{grant.Authenticator}, source.ClaimPath...)
			conditions = append(conditions, jwtClaimPrincipal(claimPath, claimValueMatcher(grant.Attributes[attribute])))
		}
	}
	if !hasClaim {
		conditions = append(conditions, jwtClaimPrincipal([]string{authenticator.Name, jwtIssuerClaimName}, exactStringValueMatcher(authenticator.JWT.Issuer)))
	}
	return andPrincipals(conditions...)
}

func exactStringValueMatcher(value string) *matcher.ValueMatcher {
	return &matcher.ValueMatcher{MatchPattern: &matcher.ValueMatcher_StringMatch{StringMatch: &matcher.StringMatcher{MatchPattern: &matcher.StringMatcher_Exact{Exact: value}}}}
}

func allowedStringValueMatcher(allowedValues []string) *matcher.ValueMatcher {
	values := make([]*matcher.ValueMatcher, 0, len(allowedValues))
	for _, value := range allowedValues {
		values = append(values, exactStringValueMatcher(value))
	}
	if len(values) == 1 {
		return values[0]
	}
	return &matcher.ValueMatcher{MatchPattern: &matcher.ValueMatcher_OrMatch{OrMatch: &matcher.OrMatcher{ValueMatchers: values}}}
}

// claimValueMatcher accepts a scalar claim or any allowed member of a list claim.
func claimValueMatcher(allowedValues []string) *matcher.ValueMatcher {
	allowedMatcher := allowedStringValueMatcher(allowedValues)
	listMatcher := &matcher.ValueMatcher{MatchPattern: &matcher.ValueMatcher_ListMatch{ListMatch: &matcher.ListMatcher{MatchPattern: &matcher.ListMatcher_OneOf{OneOf: allowedMatcher}}}}
	return &matcher.ValueMatcher{MatchPattern: &matcher.ValueMatcher_OrMatch{OrMatch: &matcher.OrMatcher{ValueMatchers: []*matcher.ValueMatcher{allowedMatcher, listMatcher}}}}
}

func jwtClaimPrincipal(claimPath []string, value *matcher.ValueMatcher) *rbac.Principal {
	return dynamicMetadataPrincipal(jwtAuthnFilterName, claimPath, value)
}

func dynamicMetadataPrincipal(namespace string, path []string, value *matcher.ValueMatcher) *rbac.Principal {
	metadataPath := make([]*matcher.MetadataMatcher_PathSegment, 0, len(path))
	for _, key := range path {
		metadataPath = append(metadataPath, metadataPathSegment(key))
	}
	return &rbac.Principal{Identifier: &rbac.Principal_SourcedMetadata{SourcedMetadata: &rbac.SourcedMetadata{MetadataSource: rbac.MetadataSource_DYNAMIC, MetadataMatcher: &matcher.MetadataMatcher{
		Filter: namespace, Path: metadataPath, Value: value,
	}}}}
}

func attributeMetadataPath(authenticator Authenticator, attribute string) (string, []string) {
	source := authenticator.Attributes[attribute]
	if source.Header != nil {
		return requestHeaderMetadataNamespace, []string{strings.ToLower(*source.Header)}
	}
	if authenticator.JWT != nil {
		return jwtAuthnFilterName, append([]string{authenticator.Name}, source.ClaimPath...)
	}
	return apiKeyMetadataNamespace, []string{apiKeyAttributeMetadataKey(attribute)}
}

func metadataPathSegment(key string) *matcher.MetadataMatcher_PathSegment {
	return &matcher.MetadataMatcher_PathSegment{Segment: &matcher.MetadataMatcher_PathSegment_Key{Key: key}}
}

